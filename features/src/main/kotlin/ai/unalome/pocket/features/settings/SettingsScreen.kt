private const val PRIVACY_STATEMENT =
    "Unalome Pocket runs language models entirely on this phone. There is no account, no analytics " +
        "and no telemetry: your messages and chats are processed and stored only here. This version " +
        "has no network access at all. When on-device models arrive, the only time the app will use " +
        "the network is to download a model you choose. Reporting a response opens an email in your " +
        "mail app; nothing is sent unless you send it."

private const val AI_NOTICE =
    "Replies are generated by a language model running on your device. They can be wrong, out of " +
        "date or offensive. Check anything important, and use “Report this response” on a reply to " +
        "tell us about a problem."

private data class License(val name: String, val licence: String, val asset: String?, val url: String)

private val LICENSES = listOf(
    License("Unalome Pocket", "Apache License 2.0", "licenses/Apache-2.0.txt", AppLinks.SOURCE_CODE),
    License("Inter typeface", "SIL Open Font License 1.1", "licenses/Inter-OFL.txt", "https://github.com/rsms/inter"),
    License("AndroidX, Jetpack Compose, Room", "Apache License 2.0", "licenses/Apache-2.0.txt", "https://developer.android.com/jetpack/androidx"),
    License("Kotlin, kotlinx.coroutines, kotlinx.serialization", "Apache License 2.0", "licenses/Apache-2.0.txt", "https://kotlinlang.org"),
)

/** About, privacy and licences. */
@Composable
fun SettingsScreen(appVersion: String, engineName: String, onBack: () -> Unit, modifier: Modifier = Modifier) {
    val uriHandler = LocalUriHandler.current
    val context = LocalContext.current
    var shownLicence by remember { mutableStateOf<License?>(null) }

    Column(modifier.fillMaxSize().background(UnalomeColor.Background).statusBarsPadding()) {
        Row(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 8.dp), verticalAlignment = Alignment.CenterVertically) {
            GlassIconButton(UnalomeIcons.Back, "Back", onBack)
            Spacer(Modifier.width(14.dp))
            Text("About", Modifier.semantics { heading() }, style = UnalomeType.Title, color = UnalomeColor.TextPrimary)
        }
        Column(
            Modifier.fillMaxSize().verticalScroll(rememberScrollState()).navigationBarsPadding().padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(20.dp),
        ) {
            Column(Modifier.fillMaxWidth().padding(vertical = 12.dp), horizontalAlignment = Alignment.CenterHorizontally) {
                UnalomeMark(height = 64.dp)
                Spacer(Modifier.height(16.dp))
                Text("Unalome Pocket", style = UnalomeType.Title, color = UnalomeColor.TextPrimary)
                Spacer(Modifier.height(4.dp))
                Text("Version $appVersion", style = UnalomeType.Footnote, color = UnalomeColor.TextTertiary)
                Text("Free and open source · Apache 2.0", style = UnalomeType.Footnote, color = UnalomeColor.TextTertiary)
            }
            Section("Privacy") { Paragraph(PRIVACY_STATEMENT) }
            Section("AI-generated replies") { Paragraph(AI_NOTICE) }
            Section("Engine") {
                Paragraph("$engineName: canned replies streamed on this phone, so the app can be tried before on-device models are added.")
            }
            Section(null) {
                LinkRow("Source code", UnalomeIcons.ExternalLink, "github.com/unalome-ai/unalome-pocket") { uriHandler.openUri(AppLinks.SOURCE_CODE) }
                Divider()
                LinkRow("unalome.ai", UnalomeIcons.ExternalLink, null) { uriHandler.openUri(AppLinks.WEBSITE) }
            }
            Section("Open-source licences") {
                LICENSES.forEachIndexed { index, licence ->
                    if (index > 0) Divider()
                    LinkRow(licence.name, UnalomeIcons.Info, licence.licence) { shownLicence = licence }
                }
            }
        }
    }

    shownLicence?.let { licence ->
        val text = remember(licence) {
            licence.asset?.let { path -> runCatching { context.assets.open(path).bufferedReader().use { it.readText() } }.getOrNull() }
                ?: licence.licence
        }
        AlertDialog(
            onDismissRequest = { shownLicence = null },
            confirmButton = { TextButton(onClick = { shownLicence = null }) { Text("Done") } },
            dismissButton = { TextButton(onClick = { uriHandler.openUri(licence.url) }) { Text("Website") } },
            title = { Text(licence.name) },
            text = {
                Column(Modifier.heightIn(max = 420.dp).verticalScroll(rememberScrollState())) {
                    Text(text, style = UnalomeType.Caption.copy(fontFamily = FontFamily.Monospace, fontSize = 11.sp, lineHeight = 15.sp), color = UnalomeColor.TextSecondary)
                }
            },
            containerColor = UnalomeColor.BackgroundRaised,
        )
    }
}

@Composable
private fun Section(title: String?, content: @Composable ColumnScope.() -> Unit) {
    Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
        if (title != null) {
            Text(title.uppercase(), Modifier.padding(start = 4.dp).semantics { heading() }, style = UnalomeType.Eyebrow, color = UnalomeColor.TextTertiary)
        }
        Column(Modifier.fillMaxWidth().glass(RoundedCornerShape(UnalomeRadius.Card)), content = content)
    }
}

@Composable
private fun Paragraph(text: String) {
    Text(text, Modifier.padding(16.dp), style = UnalomeType.Callout, color = UnalomeColor.TextSecondary)
}

@Composable
private fun Divider() = HorizontalDivider(Modifier.padding(start = 16.dp), color = UnalomeColor.GlassBorder)

@Composable
private fun LinkRow(title: String, icon: ImageVector, subtitle: String?, onClick: () -> Unit) {
    Row(
        Modifier.fillMaxWidth().clickable(role = Role.Button, onClick = onClick).padding(horizontal = 16.dp, vertical = 14.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(Modifier.weight(1f)) {
            Text(title, style = UnalomeType.Callout.copy(fontSize = 16.sp), color = UnalomeColor.TextPrimary)
            if (subtitle != null) Text(subtitle, style = UnalomeType.Footnote, color = UnalomeColor.TextTertiary)
        }
        Icon(icon, null, Modifier.size(20.dp), tint = UnalomeColor.TextTertiary)
    }
}
